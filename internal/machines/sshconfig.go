package machines

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

const configHeader = "# Generated by athome; do not edit. athome machine commands rewrite this file.\n"

// SSHDir is ~/.ssh/athome, which holds the generated config and pinned host keys.
func SSHDir(home string) string { return filepath.Join(home, ".ssh", "athome") }

func KnownHosts(home string) string { return filepath.Join(SSHDir(home), "known_hosts") }

// proxyCommand turns a jump [user@]host[:port] into the ssh command that
// forwards stdio through it. Validate guarantees host does not start with "-".
func proxyCommand(jump string) string {
	user, rest, hasUser := strings.Cut(jump, "@")
	if !hasUser {
		user, rest = "", jump
	}
	host, port, hasPort := strings.Cut(rest, ":")
	cmd := "ssh -W [%h]:%p"
	if hasPort {
		cmd += " -p " + port
	}
	if user != "" {
		cmd += " -l " + user
	}
	return cmd + " " + host
}

// block renders one Host block. A login block is the one Box.Login uses: no
// laptop key, no shared connection, and the jump as a ProxyCommand.
func block(m Machine, laptopKeyFile string, login bool) string {
	var b strings.Builder
	line := func(format string, a ...any) { fmt.Fprintf(&b, "    "+format+"\n", a...) }
	fmt.Fprintf(&b, "Host %s\n", m.Name)
	line("HostName %s", m.Target)
	line("User %s", m.User)
	line("Port %d", m.port())
	if m.Jump != "" {
		if login {
			line("ProxyCommand %s", proxyCommand(m.Jump))
		} else {
			line("ProxyJump %s", m.Jump)
		}
	}
	if !login {
		line("IdentityFile ~/.ssh/%s", laptopKeyFile)
	}
	line("IdentitiesOnly yes")
	if m.ForwardAgent {
		line("ForwardAgent yes")
	} else {
		line("ForwardAgent no")
	}
	line("HostKeyAlias %s", m.Name)
	line("UserKnownHostsFile ~/.ssh/athome/known_hosts")
	line("StrictHostKeyChecking yes")
	if login {
		line("ControlPath none")
	} else {
		line("ControlMaster auto")
		line("ControlPath ~/.ssh/athome/cm-%%C")
		line("ControlPersist 10m")
	}
	return b.String()
}

// SSHConfig renders the generated config, one block per machine in name order
// (ms is expected sorted). laptopKeyFile is the key's base name.
func SSHConfig(ms []Machine, laptopKeyFile string) string {
	var b strings.Builder
	b.WriteString(configHeader)
	for _, m := range ms {
		b.WriteString("\n" + block(m, laptopKeyFile, false))
	}
	return b.String()
}

// CheckInclude fails unless ~/.ssh/config pulls in the generated config.
func CheckInclude(home string) error {
	data, err := os.ReadFile(filepath.Join(home, ".ssh", "config"))
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	for _, l := range strings.Split(string(data), "\n") {
		if f := strings.Fields(l); len(f) == 2 && strings.EqualFold(f[0], "Include") && f[1] == "athome/config" {
			return nil
		}
	}
	return errors.New("~/.ssh/config does not include athome/config; run chezmoi apply ~/.ssh/config")
}
